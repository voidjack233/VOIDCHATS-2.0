// Package account implements proof-of-possession registration. Challenges are
// process-local, single-use capabilities; restarting the process invalidates them.
package account

import (
	"bytes"
	"context"
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"strconv"
	"strings"
	"sync"
	"time"
	"unicode"
	"unicode/utf8"

	"filippo.io/edwards25519"
)

var (
	ErrInvalidInput     = errors.New("invalid registration input")
	ErrInvalidChallenge = errors.New("challenge missing, expired, or already used")
	ErrInvalidSignature = errors.New("invalid signature")
	ErrCapacity         = errors.New("registration capacity reached")
	ErrDuplicateKey     = errors.New("authentication key already registered")
	ErrIDCollision      = errors.New("VOID-ID collision")
	ErrUnavailable      = errors.New("registration temporarily unavailable")
)

type Account struct {
	VoidID    string    `json:"void_id"`
	Username  string    `json:"username"`
	CreatedAt time.Time `json:"created_at"`
}

type Challenge struct {
	ChallengeID string    `json:"challenge_id"`
	Message     string    `json:"message"`
	ExpiresAt   time.Time `json:"expires_at"`
}

type Repository interface {
	Insert(context.Context, int64, string, []byte) (Account, error)
}

type IDGenerator interface {
	Next(context.Context) (int64, error)
}

type Options struct {
	ChallengeTTL  time.Duration
	MaxChallenges int
}

type pending struct {
	username  string
	publicKey []byte
	message   []byte
	expiresAt time.Time
}

type Service struct {
	repo       Repository
	ids        IDGenerator
	opts       Options
	now        func() time.Time
	rand       io.Reader
	mu         sync.Mutex
	challenges map[string]pending
}

func NewService(repo Repository, ids IDGenerator, opts Options) (*Service, error) {
	if repo == nil || ids == nil || opts.ChallengeTTL <= 0 || opts.ChallengeTTL > 10*time.Minute || opts.MaxChallenges < 1 || opts.MaxChallenges > 100000 {
		return nil, errors.New("invalid account service configuration")
	}
	return &Service{repo: repo, ids: ids, opts: opts, now: time.Now, rand: rand.Reader, challenges: make(map[string]pending)}, nil
}

func validUsername(username string) bool {
	if !utf8.ValidString(username) || strings.TrimSpace(username) != username {
		return false
	}
	n := utf8.RuneCountInString(username)
	if n < 1 || n > 32 {
		return false
	}
	for _, r := range username {
		if unicode.IsControl(r) || unicode.Is(unicode.Cf, r) {
			return false
		}
	}
	return true
}

// A valid signature alone is not proof of a private key for small-order public
// points (including the identity). Require canonical nonidentity prime-order
// points, which includes every key generated by ed25519.GenerateKey. Multiplying
// by 8 removes torsion; multiplying back by inverse(8) must recover the point.
func validPublicKey(key []byte) bool {
	if len(key) != ed25519.PublicKeySize {
		return false
	}
	p, err := new(edwards25519.Point).SetBytes(key)
	if err != nil || !bytes.Equal(p.Bytes(), key) {
		return false
	}
	identity := edwards25519.NewIdentityPoint()
	cofactored := new(edwards25519.Point).MultByCofactor(p)
	if cofactored.Equal(identity) == 1 {
		return false
	}
	var eightBytes [32]byte
	eightBytes[0] = 8
	eight, err := new(edwards25519.Scalar).SetCanonicalBytes(eightBytes[:])
	if err != nil {
		return false
	}
	inverseEight := new(edwards25519.Scalar).Invert(eight)
	return new(edwards25519.Point).ScalarMult(inverseEight, cofactored).Equal(p) == 1
}

func (s *Service) Challenge(username string, publicKey []byte) (Challenge, error) {
	if !validUsername(username) || !validPublicKey(publicKey) {
		return Challenge{}, ErrInvalidInput
	}
	// Both the opaque lookup token and nonce use 256 bits of OS randomness.
	var entropy [64]byte
	if _, err := io.ReadFull(s.rand, entropy[:]); err != nil {
		return Challenge{}, ErrUnavailable
	}
	id := base64.RawURLEncoding.EncodeToString(entropy[:32])
	nonce := base64.RawURLEncoding.EncodeToString(entropy[32:])
	now := s.now()
	expires := now.Add(s.opts.ChallengeTTL)
	// Sign the decoded message verbatim. Base64 field encoding and a fixed
	// domain/version make the framing unambiguous and bind all registration data.
	message := []byte("VOID-NOTHINGNESS:register:v1\n" + id + "\n" + expires.UTC().Format(time.RFC3339Nano) + "\n" +
		base64.StdEncoding.EncodeToString(publicKey) + "\n" + base64.StdEncoding.EncodeToString([]byte(username)) + "\n" + nonce + "\n")
	s.mu.Lock()
	defer s.mu.Unlock()
	for token, p := range s.challenges {
		if !now.Before(p.expiresAt) {
			delete(s.challenges, token)
		}
	}
	if len(s.challenges) >= s.opts.MaxChallenges {
		return Challenge{}, ErrCapacity
	}
	if _, exists := s.challenges[id]; exists {
		return Challenge{}, ErrUnavailable // Never overwrite even on RNG collision.
	}
	s.challenges[id] = pending{username: username, publicKey: append([]byte(nil), publicKey...), message: message, expiresAt: expires}
	return Challenge{ChallengeID: id, Message: base64.StdEncoding.EncodeToString(message), ExpiresAt: expires.UTC()}, nil
}

func (s *Service) Register(ctx context.Context, challengeID string, signature []byte) (Account, error) {
	if err := ctx.Err(); err != nil {
		return Account{}, err
	}
	if len(challengeID) != 43 || len(signature) != ed25519.SignatureSize {
		return Account{}, ErrInvalidInput
	}
	if _, err := base64.RawURLEncoding.Strict().DecodeString(challengeID); err != nil {
		return Account{}, ErrInvalidInput
	}
	s.mu.Lock()
	p, exists := s.challenges[challengeID]
	delete(s.challenges, challengeID)
	s.mu.Unlock()
	// Consumption happens before verification/database access. Failed signatures,
	// cancellation and ambiguous database commits require a fresh challenge.
	if !exists || !s.now().Before(p.expiresAt) {
		return Account{}, ErrInvalidChallenge
	}
	if !ed25519.Verify(ed25519.PublicKey(p.publicKey), p.message, signature) {
		return Account{}, ErrInvalidSignature
	}
	for range 5 {
		if err := ctx.Err(); err != nil {
			return Account{}, err
		}
		id, err := s.ids.Next(ctx)
		if err != nil || id <= 0 {
			if ctx.Err() != nil {
				return Account{}, ctx.Err()
			}
			return Account{}, ErrUnavailable
		}
		result, err := s.repo.Insert(ctx, id, p.username, p.publicKey)
		if errors.Is(err, ErrIDCollision) {
			continue
		}
		if err == nil {
			// Reject a broken repository result instead of publishing another ID.
			if result.VoidID != strconv.FormatInt(id, 10) {
				return Account{}, ErrUnavailable
			}
			return result, nil
		}
		if errors.Is(err, ErrDuplicateKey) {
			return Account{}, ErrDuplicateKey
		}
		if ctx.Err() != nil {
			return Account{}, ctx.Err()
		}
		return Account{}, ErrUnavailable
	}
	return Account{}, fmt.Errorf("%w: identifier retries exhausted", ErrUnavailable)
}
